def _filter_commands_by_scope(
    commands: List[CommandSequence],
    phase: Optional[str] = None,
    checkpoint: Optional[str] = None,
) -> List[CommandSequence]:
    """
    Filter commands by phase and/or checkpoint.

    - If phase is provided, only commands with CommandSequence.phase matching (case-insensitive) are kept.
    - If checkpoint is provided, only commands with CommandSequence.checkpoint matching are kept.
    - If both are provided, both conditions must match.
    """
    if not phase and not checkpoint:
        return commands

    phase_lower = phase.lower() if phase else None
    checkpoint_lower = checkpoint.lower() if checkpoint else None

    filtered: List[CommandSequence] = []
    for cmd in commands:
        if phase_lower:
            if not cmd.phase or cmd.phase.lower() != phase_lower:
                continue
        if checkpoint_lower:
            if not cmd.checkpoint or cmd.checkpoint.lower() != checkpoint_lower:
                continue
        filtered.append(cmd)

    return filtered


def main():
    """Main entry point for the analyzer."""
    parser = argparse.ArgumentParser(
        description="Analyze pexpect session logs and generate automation code",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Analyze a session log
  python session_analyzer.py session.log

  # Generate pexpect script
  python session_analyzer.py session.log --format pexpect

  # Generate JSON report
  python session_analyzer.py session.log --format json > report.json

  # Generate markdown report
  python session_analyzer.py session.log --format markdown > report.md

  # Generate pexpect script for a specific phase
  python session_analyzer.py session.log --format pexpect --phase "MIGRATION PHASE"

  # Generate pexpect script from a specific checkpoint
  python session_analyzer.py session.log --format pexpect --checkpoint "after_login"
        """,
    )

    parser.add_argument(
        "log_file",
        type=Path,
        help="Path to the session log file",
    )

    parser.add_argument(
        "--format",
        choices=["summary", "json", "markdown", "pexpect", "patterns"],
        default="summary",
        help="Output format (default: summary)",
    )

    parser.add_argument(
        "--output",
        type=Path,
        help="Output file (default: stdout)",
    )

    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Verbose output during analysis",
    )

    parser.add_argument(
        "--phase",
        help="Only include commands from this phase when generating pexpect script",
    )

    parser.add_argument(
        "--checkpoint",
        help="Only include commands from this checkpoint when generating pexpect script",
    )

    args = parser.parse_args()

    # Check if log file exists
    if not args.log_file.exists():
        print(f"❌ Error: Log file not found: {args.log_file}", file=sys.stderr)
        sys.exit(1)

    try:
        # Analyze the session
        analyzer = SessionAnalyzer(args.log_file)
        analysis = analyzer.analyze()

        # Generate output
        if args.format == "summary":
            output = ReportGenerator.generate_summary(analysis)
        elif args.format == "json":
            output = ReportGenerator.generate_json(analysis)
        elif args.format == "markdown":
            output = ReportGenerator.generate_markdown(analysis)
        elif args.format == "pexpect":
            scope = {
                k: v
                for k, v in {
                    "phase": args.phase,
                    "checkpoint": args.checkpoint,
                }.items()
                if v
            }

            commands = analysis.commands
            if scope:
                commands = _filter_commands_by_scope(
                    commands,
                    phase=scope.get("phase"),
                    checkpoint=scope.get("checkpoint"),
                )

            output = PexpectCodeGenerator.generate_script(
                commands,
                analysis.patterns,
                analysis.session_id,
                scope if scope else None,
            )
        elif args.format == "patterns":
            output = PexpectCodeGenerator.generate_patterns_module(analysis.patterns)
        else:
            output = ReportGenerator.generate_summary(analysis)

        # Write output
        if args.output:
            with args.output.open("w", encoding="utf-8") as f:
                f.write(output)
            print(f"✅ Output written to: {args.output}")
        else:
            print(output)

    except Exception as e:
        print(f"❌ Error during analysis: {e}", file=sys.stderr)
        if args.verbose:
            import traceback

            traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
